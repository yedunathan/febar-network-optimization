# COMMAND ----------

dbutils.widgets.text("catalog", "cpg_demos")
dbutils.widgets.text("genie_space_id", "")
CAT = dbutils.widgets.get("catalog")
SPACE = dbutils.widgets.get("genie_space_id")
G = f"{CAT}.netopt_gold"
assert SPACE, "genie_space_id parameter is required"

from databricks.sdk import WorkspaceClient
w = WorkspaceClient()


def ask(question: str):
    msg = w.genie.start_conversation_and_wait(SPACE, question)
    out = {"question": question, "status": msg.status.value if msg.status else None, "text": [], "sql": None, "columns": [], "rows": []}
    for att in msg.attachments or []:
        if att.text and att.text.content:
            out["text"].append(att.text.content)
        if att.query:
            out["sql"] = att.query.query
            if att.query.description:
                out["text"].append(att.query.description)
            res = w.genie.get_message_attachment_query_result(SPACE, msg.conversation_id, msg.message_id, att.attachment_id)
            sr = res.statement_response
            if sr and sr.manifest and sr.manifest.schema:
                out["columns"] = [c.name for c in sr.manifest.schema.columns]
                out["rows"] = (sr.result.data_array or []) if sr.result else []
    return out


def show(r, max_rows=10):
    print("=" * 110)
    print(f"Q: {r['question']}   [status={r['status']}]")
    for t in r["text"]:
        print(f"A: {t}")
    if r["sql"]:
        print("SQL generated by Genie:\n  " + r["sql"].strip().replace("\n", "\n  "))
    if r["columns"]:
        print("Result:", " | ".join(r["columns"]))
        for row in r["rows"][:max_rows]:
            print("   ", " | ".join("" if v is None else str(v) for v in row))
        if len(r["rows"]) > max_rows:
            print(f"    ... {len(r['rows'])} rows")

# COMMAND ----------

QUESTIONS = [
    "How much did out-of-route freight cost us in excess of plan over the last 3 months?",
    "Which 10 lanes have the highest expected monthly leakage?",
    "Which product families drive the most costly out-of-route moves?",
    "What actions are recommended for the high risk lanes?",
    "What share of shipped cases moved out of route in the latest month?",
    "How many reconstructed routes happened but were not planned, and what was their total cost impact?",
]
results = []
for q in QUESTIONS:
    r = ask(q)
    results.append(r)
    show(r)

