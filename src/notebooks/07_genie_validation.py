def first_number(r):
    for row in r["rows"]:
        for v in row:
            try:
                return float(v)
            except (TypeError, ValueError):
                continue
    return None


expected_high = spark.sql(f"SELECT count(*) FROM {G}.lane_action_queue WHERE risk_tier = 'HIGH'").first()[0]
r = ask("How many HIGH risk lanes are in the action queue? Return just the count.")
show(r)
print(f"CHECK high-risk lane count: genie={first_number(r)} expected={expected_high} -> "
      f"{'PASS' if first_number(r) == expected_high else 'MISMATCH'}")

expected_2026 = spark.sql(f"""SELECT round(sum(total_cost_impact), 0) FROM {G}.oor_analysis
                              WHERE drill_tab = 'costly_oor' AND year_month >= '2026-01'""").first()[0]
r = ask("What was the total costly out-of-route leakage in 2026 (year_month from 2026-01)? Return one number in USD.")
show(r)
g = first_number(r)
ok = g is not None and abs(g - float(expected_2026)) <= max(1.0, 0.001 * float(expected_2026))
print(f"CHECK 2026 leakage: genie={g} expected={expected_2026} -> {'PASS' if ok else 'MISMATCH'}")
